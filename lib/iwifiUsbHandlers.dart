  ISO15765_250KB_11BIT_CAN(0x00),
  ISO15765_250Kb_29BIT_CAN(0x01),
  ISO15765_500KB_11BIT_CAN(0x02),

  ISO15765_500KB_29BIT_CAN(0x04),
  ISO15765_1MB_11BIT_CAN(0x05),
  ISO15765_1MB_29BIT_CAN(0x06),

  I250KB_11BIT_CAN(0x07),
  I250KB_29BIT_CAN(0x08),
  I500KB_11BIT_CAN(0x09),
  I500KB_29BIT_CAN(0x0A),

  I1MB_11BIT_CAN(0x0B),
  I1MB_29BIT_CAN(0x0C),

  OE_IVN_250KBPS_11BIT_CAN(0x0D),
  OE_IVN_250KBPS_29BIT_CAN(0x0E),
  OE_IVN_500KBPS_11BIT_CAN(0x0F),
  OE_IVN_500KBPS_29BIT_CAN(0x010),

  OE_IVN_1MBPS_11BIT_CAN(0x11),
  OE_IVN_1MBPS_29BIT_CAN(0x12),

  CANOPEN_125KBPS_11BIT_CAN(0x13),
  CANOPEN_500KBPS_11BIT_CAN(0x14),

  XMODEM_125KBPS_11BIT_CAN(0x18),
  XMODEM_500KBPS_11BIT_CAN(0x1A),
  XMODEM_500KBPS_29BIT_CAN(0x1B),

  XMODEM_125KBPS_29BIT_CAN(0x21),
  ISO14230_4KWP_FAST_INIT(0x19);

  final int value;
